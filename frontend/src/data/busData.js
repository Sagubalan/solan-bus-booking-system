/** Search buses from demo data */
export function searchBuses({ from = '', to = '', type = '', maxPrice = Infinity, timeFilter = '' }) {
  return SOUTH_INDIAN_BUSES.filter(bus => {
    const matchFrom = !from || bus.from.toLowerCase().includes(from.toLowerCase())
    const matchTo   = !to   || bus.to.toLowerCase().includes(to.toLowerCase())
    const matchType = !type || bus.type === type
    const matchPrice = bus.price <= maxPrice

    let matchTime = true
    if (timeFilter === 'morning')   matchTime = parseInt(bus.departure) >= 5  && parseInt(bus.departure) < 12
    if (timeFilter === 'afternoon') matchTime = parseInt(bus.departure) >= 12 && parseInt(bus.departure) < 17
    if (timeFilter === 'evening')   matchTime = parseInt(bus.departure) >= 17 && parseInt(bus.departure) < 21
    if (timeFilter === 'night')     matchTime = parseInt(bus.departure) >= 21 || parseInt(bus.departure) < 5

    return matchFrom && matchTo && matchType && matchPrice && matchTime
  })
}
